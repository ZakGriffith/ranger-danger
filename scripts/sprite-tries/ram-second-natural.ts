function cluster(put: HdPut, x: number, y: number, w: number, h: number, shade: Paint, light: Paint) {
  poly(put, [[x-w*.45,y-h*.15],[x-w*.35,y-h*.65],[x+w*.15,y-h*.75],[x+w*.5,y-h*.2],[x+w*.4,y+h*.3],[x,y+h*.5],[x-w*.4,y+h*.2]], shade);
  poly(put, [[x-w*.32,y-h*.2],[x-w*.2,y-h*.5],[x+w*.12,y-h*.55],[x+w*.32,y-h*.15],[x,y-h*.04]], light);
}

function coil(put: HdPut, cx: number, cy: number, rx: number, ry: number, colors: HornPalette, far = false) {
  for (let y = Math.floor(cy-ry-1); y <= cy+ry+1; y++) {
    for (let x = Math.floor(cx-rx-1); x <= cx+rx+1; x++) {
      const dx = (x+.5-cx)/rx, dy = (y+.5-cy)/ry;
      const radius = Math.hypot(dx,dy);
      const angle = Math.atan2(dy,dx);
      const ripple = .014*Math.sin(angle*12);
      if (radius > 1+ripple || radius < .37) continue;
      const rim = radius > .89 || radius < .45;
      const ridge = Math.sin(angle*13+radius*2) > .87;
      const lit = -dx*.43-dy*.76;
      const tone = rim ? (lit > .2 ? 2 : 0) : ridge ? (lit > 0 ? 2 : 1) : lit > .2 ? 4 : lit > -.5 ? 3 : 2;
      put(x,y,colors[Math.max(0,tone-(far?1:0))]);
    }
  }
  poly(put, [[cx+rx*.56,cy-ry*.19],[cx+rx*.78,cy+ry*.04],[cx+rx*.52,cy+ry*.4],[cx+rx*.08,cy+ry*.48],[cx-rx*.23,cy+ry*.19],[cx-rx*.12,cy-ry*.04],[cx+rx*.12,cy+ry*.1],[cx+rx*.27,cy+ry*.22],[cx+rx*.43,cy+ry*.12]], colors[1]);
  line(put,cx+rx*.48,cy+ry*.3,cx+rx*.14,cy+ry*.29,colors[3],2);
  line(put,cx+rx*.13,cy+ry*.29,cx-rx*.08,cy+ry*.08,colors[2],2);
}

function hoof(put: HdPut, x: number, y: number, width: number, near = true) {
  poly(put, [[x+1,y-2],[x+width-2,y-2],[x+width,y+3],[x+width,y+6],[x,y+6],[x-1,y+3]], '#2c2927');
  rect(put,x+1,y,width-2,2,near?'#796a59':'#51473f');
  rect(put,x+Math.floor(width*.54),y+2,1,4,'#181d1c');
}

