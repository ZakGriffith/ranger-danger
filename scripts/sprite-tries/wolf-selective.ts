export const drawOutlinedSelectiveWolf: HdDraw = (put, raw) => {
  const pixels = new Map<number, Paint>();
  drawSelectiveWolf((x, y, paint) => {
    if (paint !== null) pixels.set(y * 64 + x, paint);
  }, raw);

  // Add one exterior pixel without covering the fur highlights or outlining the internal anatomy.
  const border = new Set<number>();
  for (const index of pixels.keys()) {
    for (const neighbor of [index - 64, index + 64, index - 1, index + 1]) {
      if (!pixels.has(neighbor)) border.add(neighbor);
    }
  }
  for (const index of border) {
    const color = pixels.has(index - 64) ? '#34404b' : pixels.has(index + 64) ? '#53616d' : '#3c4854';
    put(index % 64, Math.floor(index / 64), color);
  }
  for (const [index, color] of pixels) put(index % 64, Math.floor(index / 64), color);
};

